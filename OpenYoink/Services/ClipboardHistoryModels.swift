import Foundation
import ImageIO
import UniformTypeIdentifiers

struct ClipboardHistoryEntry: Codable, Identifiable, Equatable, Sendable {
    enum Content: Codable, Equatable, Sendable {
        case text(String)
        case url(String)
        case image(Data, type: String)

        var byteCount: Int {
            switch self {
            case .text(let value), .url(let value): value.utf8.count
            case .image(let data, _): data.count
            }
        }

        var searchText: String {
            switch self {
            case .text(let value), .url(let value): value
            case .image: ""
            }
        }

        /// Row title: text copied from a terminal or chat often starts with
        /// blank lines, which would leave a two-line title visibly empty.
        var previewText: String {
            String(searchText.drop(while: { $0.isWhitespace || $0.isNewline }))
        }

        var isValid: Bool {
            switch self {
            case .text(let value):
                return !value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
                    && byteCount <= ClipboardHistoryPolicy.maximumTextBytes
            case .url(let value):
                return byteCount <= ClipboardHistoryPolicy.maximumTextBytes
                    && URL(string: value).map {
                        ["http", "https"].contains($0.scheme?.lowercased() ?? "") && !($0.host ?? "").isEmpty
                    } == true
            case .image(let data, let type):
                guard !data.isEmpty, data.count <= ClipboardHistoryPolicy.maximumImageBytes,
                      ClipboardHistoryPolicy.storedImageTypes.contains(type),
                      let source = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
                      CGImageSourceGetCount(source) == 1,
                      CGImageSourceGetType(source) as String? == type,
                      let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
                      let width = properties[kCGImagePropertyPixelWidth] as? Int,
                      let height = properties[kCGImagePropertyPixelHeight] as? Int else { return false }
                return width > 0 && height > 0 && width <= 16_384 && height <= 16_384
                    && width * height <= 32_000_000
            }
        }
    }

    let id: UUID
    var copiedAt: Date
    let content: Content
    var isFavorite: Bool

    init(id: UUID = UUID(), copiedAt: Date = Date(), content: Content, isFavorite: Bool = false) {
        self.id = id
        self.copiedAt = copiedAt
        self.content = content
        self.isFavorite = isFavorite
    }

    private enum CodingKeys: String, CodingKey { case id, copiedAt, content, isFavorite }
    init(from decoder: Decoder) throws {
        let values = try decoder.container(keyedBy: CodingKeys.self)
        id = try values.decode(UUID.self, forKey: .id)
        copiedAt = try values.decode(Date.self, forKey: .copiedAt)
        content = try values.decode(Content.self, forKey: .content)
        isFavorite = try values.decodeIfPresent(Bool.self, forKey: .isFavorite) ?? false
    }
}
enum ClipboardContentFilter: String, CaseIterable, Identifiable {
    case all, favorites, text, links, images
    var id: Self { self }
    var title: String {
        switch self {
        case .all: String(localized: "All")
        case .favorites: String(localized: "Favorites")
        case .text: String(localized: "Text")
        case .links: String(localized: "Links")
        case .images: String(localized: "Images")
        }
    }
    func includes(_ entry: ClipboardHistoryEntry) -> Bool {
        switch (self, entry.content) {
        case (.all, _), (.text, .text), (.links, .url), (.images, .image): true
        case (.favorites, _): entry.isFavorite
        default: false
        }
    }
}

enum ClipboardHistoryPolicy {
    static let maximumTextBytes = 256 * 1_024
    nonisolated static let maximumImageBytes = 5 * 1_024 * 1_024
    static let maximumTotalBytes = 20 * 1_024 * 1_024
    // JSON escaping and base64 can be larger than the decoded content budget.
    static let maximumEncodedBytes = 64 * 1_024 * 1_024
    static let maximumEntries = 30
    static let supportedEntryLimits = [30, 100, 300]
    static let maximumFavorites = 30
    static let sensitiveTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "PasswordPboardType",
    ]

    /// PNG and TIFF bitmaps are kept as copied. JPEG holds a JPEG file copied
    /// in Finder, or an image re-encoded because its PNG/TIFF exceeded
    /// `maximumImageBytes` (typically photos).
    nonisolated static let storedImageTypes: Set<String> = ["public.png", "public.tiff", "public.jpeg"]

    /// Copied files are not recorded, except when the copy is really an image
    ///:
    /// - an app that copies an image as its bitmap plus a link to the file it
    ///   came from (WeChat links its cache file): the bitmap is recorded;
    /// - a single image file copied in Finder, which carries no bitmap: the
    ///   file's image is recorded.
    /// Several files, or any non-image file, stay excluded.
    static func permits(types: Set<String>, fileURLs: [URL] = [], sourceIsIgnored: Bool) -> Bool {
        guard !sourceIsIgnored, types.isDisjoint(with: sensitiveTypes) else { return false }
        guard types.contains("public.file-url") else { return true }
        return isImageCopy(types: types, fileURLs: fileURLs)
    }

    static func carriesBitmap(_ types: Set<String>) -> Bool {
        types.contains("public.png") || types.contains("public.tiff")
    }

    static func isImageCopy(types: Set<String>, fileURLs: [URL]) -> Bool {
        guard !fileURLs.isEmpty, fileURLs.allSatisfy(isImageFile) else { return false }
        return carriesBitmap(types) || fileURLs.count == 1
    }

    nonisolated static func isImageFile(_ url: URL) -> Bool {
        url.isFileURL && UTType(filenameExtension: url.pathExtension)?.conforms(to: .image) == true
    }

    /// Image files above this are not read at all (a RAW photo, a huge scan).
    nonisolated static let maximumSourceImageFileBytes = 64 * 1_024 * 1_024

    /// Loads the image of a copied image file: kept as is when it is a PNG,
    /// TIFF or JPEG that fits, otherwise re-encoded (HEIC, WebP, large PNG…).
    nonisolated static func imageFromFile(_ url: URL) -> (data: Data, type: String)? {
        guard isImageFile(url),
              let size = (try? url.resourceValues(forKeys: [.fileSizeKey]))?.fileSize,
              size > 0, size <= maximumSourceImageFileBytes,
              let data = try? Data(contentsOf: url, options: .mappedIfSafe),
              let source = CGImageSourceCreateWithData(data as CFData, nil),
              let type = CGImageSourceGetType(source) as String? else { return nil }
        if storedImageTypes.contains(type), data.count <= maximumImageBytes, CGImageSourceGetCount(source) == 1 {
            return (Data(data), type)
        }
        return reencodedImage(data)
    }

    /// Re-encodes a bitmap whose copied PNG/TIFF is over `maximumImageBytes`.
    /// TIFF is usually uncompressed (a 1920×1080 copy is ~8 MB), so PNG often
    /// fits; photos fall back to JPEG. Returns nil when neither fits. Runs off
    /// the main actor: encoding a large image takes a noticeable moment.
    nonisolated static func reencodedImage(_ data: Data) -> (data: Data, type: String)? {
        let options = [kCGImageSourceShouldCache: false] as CFDictionary
        guard let source = CGImageSourceCreateWithData(data as CFData, options),
              CGImageSourceGetCount(source) >= 1,
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else { return nil }
        if let png = encode(image, as: .png, quality: nil), png.count <= maximumImageBytes {
            return (png, UTType.png.identifier)
        }
        guard let opaque = flattenedOntoWhite(image),
              let jpeg = encode(opaque, as: .jpeg, quality: 0.9),
              jpeg.count <= maximumImageBytes else { return nil }
        return (jpeg, UTType.jpeg.identifier)
    }

    nonisolated private static func encode(_ image: CGImage, as type: UTType, quality: Double?) -> Data? {
        let output = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(output, type.identifier as CFString, 1, nil)
        else { return nil }
        let properties = quality.map { [kCGImageDestinationLossyCompressionQuality: $0] as CFDictionary }
        CGImageDestinationAddImage(destination, image, properties)
        guard CGImageDestinationFinalize(destination) else { return nil }
        return output as Data
    }

    /// JPEG has no alpha; ImageIO would turn transparent pixels black.
    nonisolated private static func flattenedOntoWhite(_ image: CGImage) -> CGImage? {
        switch image.alphaInfo {
        case .none, .noneSkipFirst, .noneSkipLast: return image
        default: break
        }
        guard let context = CGContext(data: nil, width: image.width, height: image.height,
                                      bitsPerComponent: 8, bytesPerRow: 0,
                                      space: CGColorSpace(name: CGColorSpace.sRGB)!,
                                      bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue) else { return nil }
        let rect = CGRect(x: 0, y: 0, width: image.width, height: image.height)
        context.setFillColor(CGColor(red: 1, green: 1, blue: 1, alpha: 1))
        context.fill(rect)
        context.draw(image, in: rect)
        return context.makeImage()
    }

    static func trimmed(_ entries: [ClipboardHistoryEntry], now: Date, retentionDays: Int,
                        entryLimit: Int = maximumEntries) -> [ClipboardHistoryEntry] {
        let cutoff = now.addingTimeInterval(-Double(max(1, retentionDays)) * 86_400)
        var result: [ClipboardHistoryEntry] = []
        var bytes = 0
        var ids = Set<UUID>()
        var favorites = 0
        var ordinary = 0
        let limit = supportedEntryLimits.contains(entryLimit) ? entryLimit : maximumEntries
        for entry in entries.sorted(by: {
            if $0.isFavorite != $1.isFavorite { return $0.isFavorite }
            return $0.copiedAt > $1.copiedAt
        }) {
            guard entry.content.isValid, entry.isFavorite || entry.copiedAt > cutoff,
                  ids.insert(entry.id).inserted,
                  !result.contains(where: { $0.content == entry.content }) else { continue }
            guard (entry.isFavorite ? favorites < maximumFavorites : ordinary < limit),
                  bytes + entry.content.byteCount <= maximumTotalBytes else { continue }
            result.append(entry)
            bytes += entry.content.byteCount
            if entry.isFavorite { favorites += 1 } else { ordinary += 1 }
        }
        return result
    }

    static func inserting(_ content: ClipboardHistoryEntry.Content, into entries: [ClipboardHistoryEntry],
                          now: Date, retentionDays: Int, entryLimit: Int = maximumEntries) -> [ClipboardHistoryEntry] {
        guard content.isValid else { return entries }
        let existing = entries.first(where: { $0.content == content })
        return trimmed([ClipboardHistoryEntry(id: existing?.id ?? UUID(), copiedAt: now,
                                             content: content, isFavorite: existing?.isFavorite ?? false)]
                       + entries.filter { $0.content != content }, now: now, retentionDays: retentionDays,
                       entryLimit: entryLimit)
    }
}
